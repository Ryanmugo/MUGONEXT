"""
=========================================================
MUGONEXT
Gemini AI Service
=========================================================
Provides AI-powered business explanation and enrichment
for recommendations generated by the deterministic
MUGONEXT recommendation engine.

Gemini does NOT calculate forecasts, confidence scores,
priority scores, or other quantitative metrics.

The MUGONEXT forecasting and recommendation engine
remains the source of truth.
"""

from __future__ import annotations

import os
from typing import Any

from dotenv import load_dotenv
from google import genai


# =========================================================
# ENVIRONMENT
# =========================================================

load_dotenv()


class GeminiService:
    """
    Service responsible for Gemini-powered business
    explanation and recommendation enrichment.
    """

    MODEL = "gemini-3.6-flash"

    def __init__(self) -> None:
        """
        Initialize the Gemini client.

        The API key is loaded exclusively from the
        GEMINI_API_KEY environment variable.
        """

        api_key = os.getenv("GEMINI_API_KEY")

        if not api_key:
            raise RuntimeError(
                "GEMINI_API_KEY is not configured."
            )

        self.client = genai.Client(
            api_key=api_key
        )

    # =====================================================
    # ENHANCE RECOMMENDATION
    # =====================================================

    def enhance_recommendation(
        self,
        *,
        recommendation_data: dict[str, Any],
    ) -> str:
        """
        Generate an AI-powered business explanation for
        an existing deterministic MUGONEXT recommendation.

        Gemini receives the structured recommendation and
        forecast signals as context.

        It does NOT modify numerical metrics.
        """

        prompt = self._build_prompt(
            recommendation_data
        )

        try:
            interaction = self.client.interactions.create(
                model=self.MODEL,
                input=prompt,
            )

            output = getattr(
                interaction,
                "output_text",
                None,
            )

            if not output:
                return (
                    "Gemini did not return an explanation. "
                    "The original MUGONEXT recommendation "
                    "remains valid."
                )

            return output.strip()

        except Exception as exc:
            # Gemini must never break the core MUGONEXT
            # recommendation engine.
            return (
                "AI explanation temporarily unavailable. "
                "The recommendation was generated using "
                "the MUGONEXT quantitative decision engine."
            )

    # =====================================================
    # PROMPT
    # =====================================================

    @staticmethod
    def _build_prompt(
        recommendation_data: dict[str, Any],
    ) -> str:
        """
        Build a controlled business-analysis prompt.
        """

        parameters = recommendation_data.get(
            "parameters",
            {},
        )

        source_data = recommendation_data.get(
            "source_data",
            {},
        )

        return f"""
You are the business intelligence explanation layer
inside MUGONEXT, an AI-powered business decision platform.

Your job is to explain an existing recommendation in
clear, practical business language.

IMPORTANT RULES:

1. Do not invent data.
2. Do not change numerical values.
3. Do not calculate a different forecast.
4. Do not change the recommendation priority.
5. Do not claim certainty.
6. Base your explanation only on the supplied MUGONEXT data.
7. The quantitative MUGONEXT engine is the source of truth.
8. Keep the explanation useful for a business manager.
9. Focus on what the business should understand and why
   the recommendation matters.
10. Do not mention internal APIs, prompts, SDKs, or
    implementation details.

MUGONEXT RECOMMENDATION

Title:
{recommendation_data.get("title")}

Category:
{recommendation_data.get("category")}

Recommendation:
{recommendation_data.get("recommendation")}

Reasoning:
{recommendation_data.get("reasoning")}

Suggested Action:
{recommendation_data.get("suggested_action")}

Expected Outcome:
{recommendation_data.get("expected_outcome")}

Priority:
{recommendation_data.get("priority")}

Priority Score:
{recommendation_data.get("priority_score")}

Impact Score:
{recommendation_data.get("impact_score")}

Confidence Score:
{recommendation_data.get("confidence_score")}

PARAMETERS

Trend:
{parameters.get("trend")}

Business Signal:
{parameters.get("business_signal")}

Volatility:
{parameters.get("volatility")}

Forecast Quality:
{parameters.get("forecast_quality")}

Confidence Level:
{parameters.get("confidence_level")}

Average Forecast:
{parameters.get("average_forecast")}

SOURCE FORECAST DATA

Percentage Change:
{source_data.get("percentage_change")}

First Forecast:
{source_data.get("first_forecast")}

Last Forecast:
{source_data.get("last_forecast")}

Average Forecast:
{source_data.get("average_forecast")}

MAPE:
{source_data.get("mape")}

Accuracy:
{source_data.get("accuracy_score")}

R-squared:
{source_data.get("r_squared")}

Write a concise business explanation in 2-4 short paragraphs.

Explain:

- what MUGONEXT detected,
- why the signal matters to the business,
- what management should pay attention to,
- and what practical consequence may occur if the signal
  is ignored.

Do not repeat the recommendation word-for-word.
Do not introduce numbers that are not provided above.
""".strip()